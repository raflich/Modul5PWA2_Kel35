-- 1. TABEL PRODUCTS (Katalog Senjata / Hardware)
CREATE TABLE IF NOT EXISTS public.products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    type TEXT NOT NULL DEFAULT 'Hardware', -- 'Pistol', 'Rifle', 'Shotgun'
    caliber TEXT NOT NULL DEFAULT 'Standard',
    price NUMERIC NOT NULL DEFAULT 0,
    description TEXT DEFAULT '',
    specs TEXT[] DEFAULT '{}',
    image_url TEXT DEFAULT '/guns/pistol.svg',
    images TEXT[] DEFAULT '{}',
    is_archived BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc', NOW()),
    updated_at TIMESTAMPTZ DEFAULT TIMEZONE('utc', NOW())
);

-- Migrasi tambahan untuk tabel yang sudah ada sebelumnya
ALTER TABLE public.products ADD COLUMN IF NOT EXISTS is_archived BOOLEAN DEFAULT FALSE;
ALTER TABLE public.products ADD COLUMN IF NOT EXISTS images TEXT[] DEFAULT '{}';

-- 2. TABEL REVIEWS (Ulasan & Rating Produk)
CREATE TABLE IF NOT EXISTS public.reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
    user_id TEXT NOT NULL,
    rating SMALLINT NOT NULL CHECK (rating >= 1 AND rating <= 5),
    comment TEXT DEFAULT '',
    likes INT DEFAULT 0,
    dislikes INT DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc', NOW())
);

ALTER TABLE public.reviews ADD COLUMN IF NOT EXISTS likes INT DEFAULT 0;
ALTER TABLE public.reviews ADD COLUMN IF NOT EXISTS dislikes INT DEFAULT 0;

-- 3. TABEL FAVORITES (Daftar Favorit Pengguna)
CREATE TABLE IF NOT EXISTS public.favorites (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
    user_id TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc', NOW()),
    CONSTRAINT unique_user_favorite UNIQUE (product_id, user_id)
);

-- Indexing untuk kecepatan pencarian & relasi join
CREATE INDEX IF NOT EXISTS idx_products_type ON public.products(type);
CREATE INDEX IF NOT EXISTS idx_reviews_product_id ON public.reviews(product_id);
CREATE INDEX IF NOT EXISTS idx_favorites_user_id ON public.favorites(user_id);

-- ============================================================================
-- 4. ROW LEVEL SECURITY (RLS) POLICIES
-- Memberi izin akses penuh (SELECT, INSERT, UPDATE, DELETE) untuk peran anon / public
-- ============================================================================

ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.reviews ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.favorites ENABLE ROW LEVEL SECURITY;

-- Products Policies
DROP POLICY IF EXISTS "Public full access to products" ON public.products;
CREATE POLICY "Public full access to products" ON public.products
    FOR ALL
    TO public
    USING (true)
    WITH CHECK (true);

-- Reviews Policies
DROP POLICY IF EXISTS "Public full access to reviews" ON public.reviews;
CREATE POLICY "Public full access to reviews" ON public.reviews
    FOR ALL
    TO public
    USING (true)
    WITH CHECK (true);

-- Favorites Policies
DROP POLICY IF EXISTS "Public full access to favorites" ON public.favorites;
CREATE POLICY "Public full access to favorites" ON public.favorites
    FOR ALL
    TO public
    USING (true)
    WITH CHECK (true);

